/**
 * Minimal, dependency-free PDF generator for demonstration brochures.
 * Produces a single-page, print-ready summary from database-backed fields.
 */

type BrochureProject = {
  name: string;
  tagline: string | null;
  address: string;
  status: string;
  startingPrice: number;
  maxPrice: number | null;
  bhkConfigs: string;
  possessionDate: Date | null;
  reraNumber: string | null;
  reraVerified: boolean;
  description: string;
  developer: { name: string };
  location: { name: string };
  amenities: { amenity: { name: string } }[];
};

const STATUS: Record<string, string> = {
  NEW_LAUNCH: "New launch",
  UNDER_CONSTRUCTION: "Under construction",
  READY_TO_MOVE: "Ready to move",
  UPCOMING: "Upcoming",
};

const escapePdf = (value: string) =>
  value
    .replace(/[₹]/g, "Rs. ")
    .replace(/[^\x20-\x7E]/g, "")
    .replace(/\\/g, "\\\\")
    .replace(/\(/g, "\\(")
    .replace(/\)/g, "\\)");

const price = (value: number) => {
  if (value >= 10_000_000) return `Rs. ${(value / 10_000_000).toFixed(2).replace(/\.?0+$/, "")} Cr`;
  return `Rs. ${(value / 100_000).toFixed(0)} L`;
};

function wrap(text: string, width = 88) {
  const words = text.split(/\s+/);
  const lines: string[] = [];
  let line = "";
  for (const word of words) {
    if ((line + " " + word).trim().length > width) {
      if (line) lines.push(line);
      line = word;
    } else {
      line = `${line} ${word}`.trim();
    }
  }
  if (line) lines.push(line);
  return lines.slice(0, 12);
}

function buildText(project: BrochureProject) {
  const commands: string[] = [];
  const ink = "0.071 0.129 0.106 rg";
  const soft = "0.247 0.314 0.278 rg";
  const brass = "0.722 0.537 0.290 rg";

  const text = (x: number, y: number, size: number, value: string, color = ink, font = "F1") =>
    `BT ${color} /${font} ${size} Tf ${x} ${y} Td (${escapePdf(value)}) Tj ET`;

  commands.push(text(56, 744, 10, "Innovations  /  DEMONSTRATION BROCHURE", brass));
  commands.push("0.722 0.537 0.290 RG 0.7 w 56 733 m 556 733 l S");
  commands.push(text(56, 690, 28, project.name));
  if (project.tagline) commands.push(text(56, 670, 11, project.tagline, soft));
  commands.push(text(56, 642, 10, `${project.developer.name}  |  ${project.location.name}`, soft));
  commands.push(text(56, 622, 10, project.address, soft));

  commands.push("0.878 0.843 0.784 RG 0.5 w 56 605 m 556 605 l S");
  commands.push(text(56, 584, 9, "STARTING PRICE", brass));
  commands.push(text(56, 564, 16, price(project.startingPrice)));
  commands.push(text(216, 584, 9, "CONFIGURATION", brass));
  commands.push(text(216, 564, 16, project.bhkConfigs.replace(/[\[\]"]/g, "").replace(/,/g, " / ")));
  commands.push(text(396, 584, 9, "STATUS", brass));
  commands.push(text(396, 564, 16, STATUS[project.status] ?? project.status));
  commands.push("0.878 0.843 0.784 RG 0.5 w 56 545 m 556 545 l S");

  commands.push(text(56, 524, 9, "POSSESSION", brass));
  commands.push(text(56, 506, 11, project.possessionDate ? project.possessionDate.toISOString().slice(0, 10) : "To be announced", ink));
  commands.push(text(216, 524, 9, "RERA", brass));
  commands.push(
    text(
      216,
      506,
      11,
      project.reraVerified && project.reraNumber ? project.reraNumber : "Not verified — sample data",
      project.reraVerified ? ink : soft,
    ),
  );
  commands.push(text(396, 524, 9, "PROPERTY TYPE", brass));
  commands.push(text(396, 506, 11, project.location.name, soft));

  commands.push(text(56, 470, 10, "ABOUT THIS PROJECT", brass));
  wrap(project.description).forEach((line, index) => {
    commands.push(text(56, 448 - index * 14, 9.5, line, soft));
  });

  const amenityLine = project.amenities.map((a) => a.amenity.name).join("  •  ");
  commands.push(text(56, 258, 10, "AMENITIES", brass));
  wrap(amenityLine, 95)
    .slice(0, 3)
    .forEach((line, index) => commands.push(text(56, 238 - index * 13, 9, line, soft)));

  commands.push("0.878 0.843 0.784 RG 0.5 w 56 190 m 556 190 l S");
  commands.push(text(56, 172, 8.5, "IMPORTANT: This is a demonstration brochure. All projects, developers, prices,", "0.482 0.376 0.259"));
  commands.push(text(56, 160, 8.5, "approvals, possession dates and RERA references are sample data and are not verified.", "0.482 0.376 0.259"));
  commands.push(text(56, 148, 8.5, "It is not a legal offer, allotment letter or broker representation. Photography is illustrative.", "0.482 0.376 0.259"));
  commands.push(text(56, 120, 8.5, "Generated by Innovations Rental Solutions  |  innovations.sample  |  Sample data only", soft));
  commands.push(text(520, 120, 8.5, "1 / 1", soft));

  return commands.join("\n");
}

export function createBrochurePdf(project: BrochureProject) {
  const content = buildText(project);
  const objects: string[] = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    `<< /Length ${Buffer.byteLength(content, "ascii")} >>\nstream\n${content}\nendstream`,
  ];

  let pdf = "%PDF-1.4\n";
  const offsets: number[] = [0];
  objects.forEach((object, index) => {
    offsets.push(Buffer.byteLength(pdf, "ascii"));
    pdf += `${index + 1} 0 obj\n${object}\nendobj\n`;
  });
  const xrefOffset = Buffer.byteLength(pdf, "ascii");
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (const offset of offsets.slice(1)) {
    pdf += `${String(offset).padStart(10, "0")} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;

  return Buffer.from(pdf, "ascii");
}

